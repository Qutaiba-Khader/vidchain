package org.websnake.vidchain.fallback.fixes

/**
 * T8.7 f8 + T9 decision 2: the cookie file handed to yt-dlp. Every line names the exact host of the page the cookies
 * belong to, host-only (include-subdomains FALSE), so yt-dlp's cookie jar sends them to that host only: a redirect or
 * a media address on another host (a CDN) never gets them. Pure (JVM-tested, NetscapeCookiesTest).
 */
object NetscapeCookies {
	fun file(cookieString: String, forUrl: String?): String {
		val domain = forUrl?.let { runCatching { java.net.URI(it).host }.getOrNull() }.orEmpty()
		val secure = if (forUrl?.startsWith("https:", ignoreCase = true) == true) "TRUE" else "FALSE"
		val sb = StringBuilder("# Netscape HTTP Cookie File\n# This file was generated by the app.\n\n")
		for (cookie in cookieString.split(";").map { it.trim() }) {
			val parts = cookie.split("=", limit = 2)
			if (parts.size == 2) sb.append("$domain\tFALSE\t/\t$secure\t2147483647\t${parts[0].trim()}\t${parts[1].trim()}\n")
		}
		return sb.toString()
	}

	/** would a cookie line of [file] be sent to [host]: only to its own host (host-only), never to another one */
	fun sentTo(file: String, host: String): Boolean = file.lineSequence().filter { it.isNotBlank() && !it.startsWith("#") }
		.any { line ->
			val f = line.split('\t')
			f.size >= 7 && ((f[1] == "FALSE" && f[0].equals(host, ignoreCase = true)) || (f[1] == "TRUE" && HostMatch.isHost(host, f[0].trimStart('.'))))
		}
}
